#!/usr/bin/env node
// Fetches the OpenStreetMap administrative boundaries of the five Potkalničko prigorje
// municipalities from Overpass, projects them into MAP_FRAME pixels (the same Web Mercator
// maths as shared/utils/games/mapFrame.ts), simplifies them and writes
// shared/utils/games/mapBoundaries.ts. Run it by hand, the app never calls it:
//
//   node scripts/map/fetch-boundaries.mjs
//
// Data © OpenStreetMap contributors, ODbL. No dependencies.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const FRAME = { west: 16.3298, east: 16.7322, south: 45.9187, north: 46.1584, width: 1600, height: 1373 }
/** Douglas-Peucker tolerance in frame pixels. */
const TOLERANCE = 0.9

/** OSM relation id → slug of the municipality area (see the areas seed). */
const RELATIONS = [
  { slug: 'grad-krizevci', relation: 8448030, name: 'Grad Križevci' },
  { slug: 'opcina-gornja-rijeka', relation: 8448032, name: 'Općina Gornja Rijeka' },
  { slug: 'opcina-kalnik', relation: 8447844, name: 'Općina Kalnik' },
  { slug: 'opcina-sveti-ivan-zabno', relation: 8447843, name: 'Općina Sveti Ivan Žabno' },
  { slug: 'opcina-sveti-petar-orehovec', relation: 8448031, name: 'Općina Sveti Petar Orehovec' }
]

const mercY = lat => Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360))
function project(lat, lng) {
  const x = (lng - FRAME.west) / (FRAME.east - FRAME.west) * FRAME.width
  const y = (mercY(FRAME.north) - mercY(lat)) / (mercY(FRAME.north) - mercY(FRAME.south)) * FRAME.height
  return [x, y]
}

async function overpass(query) {
  const res = await fetch('https://overpass-api.de/api/interpreter', {
    method: 'POST',
    headers: { 'User-Agent': 'potkalnicki-zapisi-map-script/1.0', 'Content-Type': 'application/x-www-form-urlencoded' },
    body: `data=${encodeURIComponent(query)}`
  })
  if (!res.ok) throw new Error(`Overpass ${res.status}`)
  return res.json()
}

/** Joins the outer ways of a relation into closed rings. */
function buildRings(members) {
  const ways = members.filter(m => m.type === 'way' && m.role === 'outer' && m.geometry?.length > 1)
    .map(m => m.geometry.map(p => [p.lat, p.lon]))
  const same = (a, b) => a[0] === b[0] && a[1] === b[1]
  const rings = []
  while (ways.length) {
    let ring = ways.shift()
    let grew = true
    while (grew && !same(ring[0], ring.at(-1))) {
      grew = false
      for (let i = 0; i < ways.length; i++) {
        const w = ways[i]
        if (same(ring.at(-1), w[0])) ring = ring.concat(w.slice(1))
        else if (same(ring.at(-1), w.at(-1))) ring = ring.concat(w.slice(0, -1).reverse())
        else if (same(ring[0], w.at(-1))) ring = w.concat(ring.slice(1))
        else if (same(ring[0], w[0])) ring = w.slice(1).reverse().concat(ring)
        else continue
        ways.splice(i, 1)
        grew = true
        break
      }
    }
    if (same(ring[0], ring.at(-1))) rings.push(ring)
    else console.warn('open ring dropped')
  }
  return rings
}

function simplify(points, tolerance) {
  if (points.length < 3) return points
  const [ax, ay] = points[0]
  const [bx, by] = points.at(-1)
  const len = Math.hypot(bx - ax, by - ay)
  let max = 0
  let index = 0
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i]
    const d = len === 0
      ? Math.hypot(px - ax, py - ay)
      : Math.abs((bx - ax) * (ay - py) - (ax - px) * (by - ay)) / len
    if (d > max) {
      max = d
      index = i
    }
  }
  if (max <= tolerance) return [points[0], points.at(-1)]
  return simplify(points.slice(0, index + 1), tolerance).slice(0, -1).concat(simplify(points.slice(index), tolerance))
}

const round = n => Math.round(n * 10) / 10

function toPath(ring) {
  // keep both ends of the closed ring, so split it in two halves to simplify it properly
  const pts = ring.map(([lat, lng]) => project(lat, lng))
  const mid = Math.floor(pts.length / 2)
  const simple = simplify(pts.slice(0, mid + 1), TOLERANCE).slice(0, -1).concat(simplify(pts.slice(mid), TOLERANCE).slice(0, -1))
  return `M${simple.map(([x, y]) => `${round(x)} ${round(y)}`).join('L')}Z`
}

const ids = RELATIONS.map(r => r.relation).join(',')
const data = await overpass(`[out:json][timeout:120];relation(id:${ids});out geom;`)

const entries = RELATIONS.map((r) => {
  const rel = data.elements.find(e => e.id === r.relation)
  if (!rel) throw new Error(`relation ${r.relation} missing`)
  if (rel.tags?.name !== r.name) throw new Error(`relation ${r.relation} is "${rel.tags?.name}", expected "${r.name}"`)
  const d = buildRings(rel.members).map(toPath).join('')
  return `  '${r.slug}': {\n    osmRelation: ${r.relation},\n    d: '${d}'\n  }`
})

const out = `// Generated by scripts/map/fetch-boundaries.mjs, do not edit by hand.
// Administrative boundaries © OpenStreetMap contributors (ODbL), simplified and projected into MAP_FRAME pixels.

export const MUNICIPALITY_BOUNDARIES: Record<string, { osmRelation: number, d: string }> = {
${entries.join(',\n')}
}
`

const target = fileURLToPath(new URL('../../shared/utils/games/mapBoundaries.ts', import.meta.url))
writeFileSync(target, out)
console.log(`wrote ${target} (${out.length} bytes)`)
